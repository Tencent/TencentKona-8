# Generate the TLCP encryption certificates that must be rejected by the
# encryption certificate chain verification. The certificates are issued by
# the intermediate CA generated by tlcp-gen-certs.sh, which must exist already.
# Run this script from this directory.

OPENSSL=tongsuo
SRC_DIR="."
OUT_DIR="."

if [ ! -f ${SRC_DIR}/tlcp-intca.crt ]; then
  echo "Run tlcp-gen-certs.sh first"
  exit 1
fi

WORK=$(mktemp -d)
trap 'rm -rf ${WORK}' EXIT

cat > ${WORK}/ee-enc.ext << EOF
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
basicConstraints=critical,CA:FALSE
keyUsage=critical,keyEncipherment,dataEncipherment,keyAgreement
EOF

cat > ${WORK}/ee-enc-eku.ext << EOF
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
basicConstraints=critical,CA:FALSE
keyUsage=critical,keyEncipherment,dataEncipherment,keyAgreement
extendedKeyUsage=codeSigning
EOF

cat > ${WORK}/ee-enc-ca.ext << EOF
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
basicConstraints=critical,CA:TRUE
keyUsage=critical,keyEncipherment,dataEncipherment,keyAgreement
EOF

cat > ${WORK}/ca.ext << EOF
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
basicConstraints=critical,CA:TRUE
keyUsage=critical,digitalSignature,keyCertSign,cRLSign
EOF

# A minimal configuration, only used by the "ca" command, which is the one
# that can set an explicit validity period.
cat > ${WORK}/ca.cnf << EOF
[ca]
default_ca = CA_default
[CA_default]
dir = ${WORK}
database = ${WORK}/index.txt
new_certs_dir = ${WORK}
serial = ${WORK}/serial
default_md = sm3
policy = policy_any
unique_subject = no
copy_extensions = none
[policy_any]
commonName = supplied
EOF
touch ${WORK}/index.txt
echo 01 > ${WORK}/serial

# gen_key <name>
gen_key() {
  $OPENSSL genpkey -algorithm ec -pkeyopt ec_paramgen_curve:SM2 \
      -pkeyopt ec_param_enc:named_curve -out ${OUT_DIR}/$1.key
}

# sign_x509 <name> <cn> <extfile> <issuer-crt> <issuer-key>
sign_x509() {
  $OPENSSL req -new -key ${OUT_DIR}/$1.key -subj "/CN=$2" -sm3 -out ${WORK}/$1.csr
  $OPENSSL x509 -extfile $3 -req -CAcreateserial -days 3650 -in ${WORK}/$1.csr -sm3 \
      -CA $4 -CAkey $5 -out ${WORK}/$1.crt.tmp
  $OPENSSL x509 -text -in ${WORK}/$1.crt.tmp > ${OUT_DIR}/$1.crt
}

# sign_expired <name> <cn> <extfile> <issuer-crt> <issuer-key>
sign_expired() {
  $OPENSSL req -new -key ${OUT_DIR}/$1.key -subj "/CN=$2" -sm3 -out ${WORK}/$1.csr
  $OPENSSL ca -batch -config ${WORK}/ca.cnf -notext -md sm3 \
      -extfile $3 -cert $4 -keyfile $5 \
      -startdate 20200101000000Z -enddate 20200102000000Z \
      -in ${WORK}/$1.csr -out ${WORK}/$1.crt.tmp
  $OPENSSL x509 -text -in ${WORK}/$1.crt.tmp > ${OUT_DIR}/$1.crt
}

##### A rogue CA that has the same subject as the intermediate CA, but a
##### different key. Certificates it issues carry the right issuer name but
##### cannot be verified with the real intermediate CA's public key.
gen_key tlcp-rogue-intca
$OPENSSL req -new -key ${OUT_DIR}/tlcp-rogue-intca.key -subj "/CN=tlcp-intca" -sm3 \
    -out ${WORK}/tlcp-rogue-intca.csr
$OPENSSL x509 -extfile ${WORK}/ca.ext -req -CAcreateserial -days 3650 \
    -in ${WORK}/tlcp-rogue-intca.csr -sm3 \
    -signkey ${OUT_DIR}/tlcp-rogue-intca.key -out ${WORK}/tlcp-rogue-intca.crt.tmp
$OPENSSL x509 -text -in ${WORK}/tlcp-rogue-intca.crt.tmp > ${WORK}/tlcp-rogue-intca.crt
# Tests also trust the rogue CA next to the real one, to check that the enc
# certificate is verified by the same CA key as the sign certificate.
cp ${WORK}/tlcp-rogue-intca.crt ${OUT_DIR}/tlcp-rogue-intca.crt

INTCA_CRT=${SRC_DIR}/tlcp-intca.crt
INTCA_KEY=${SRC_DIR}/tlcp-intca.key

for role in server client; do
  CN=tlcp-${role}

  ##### The issuer name is right, but it is signed by the rogue key
  gen_key tlcp-${role}-enc-forged
  sign_x509 tlcp-${role}-enc-forged ${CN} ${WORK}/ee-enc.ext \
      ${WORK}/tlcp-rogue-intca.crt ${OUT_DIR}/tlcp-rogue-intca.key

  ##### A CA certificate in the enc position
  gen_key tlcp-${role}-enc-ca
  sign_x509 tlcp-${role}-enc-ca ${CN} ${WORK}/ee-enc-ca.ext ${INTCA_CRT} ${INTCA_KEY}

  ##### An extended key usage that does not permit TLS
  gen_key tlcp-${role}-enc-eku
  sign_x509 tlcp-${role}-enc-eku ${CN} ${WORK}/ee-enc-eku.ext ${INTCA_CRT} ${INTCA_KEY}

  ##### Expired
  gen_key tlcp-${role}-enc-expired
  sign_expired tlcp-${role}-enc-expired ${CN} ${WORK}/ee-enc.ext ${INTCA_CRT} ${INTCA_KEY}
done

# The "openssl x509 -text" dump can leave trailing whitespace on some
# extension header lines; strip it so the generated certs stay clean.
sed -i 's/[[:space:]]*$//' ${OUT_DIR}/tlcp-*-enc-{forged,ca,eku,expired}.crt ${OUT_DIR}/tlcp-rogue-intca.crt
